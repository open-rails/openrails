package schemasnapshot

import (
	"bytes"
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"log/slog"
	"slices"
	"strings"
	"time"

	"github.com/ClickHouse/clickhouse-go/v2"
	"github.com/ClickHouse/clickhouse-go/v2/lib/driver"

	"github.com/open-rails/openrails/internal/eventstore"
)

const (
	// ClickHouseFile lists the event store's schema, relative to the
	// repository.
	ClickHouseFile = "api/clickhouse.txt"
	// ClickHouseVersion is the server line the list is read from: ClickHouse
	// prints definitions differently across releases.
	ClickHouseVersion = "26.8"
)

// ErrClickHouseStale reports an api/clickhouse.txt that is not what the
// event store's migrations install.
var ErrClickHouseStale = fmt.Errorf("%s is stale: run go run ./scripts/contracts -write -clickhouse ADDR naming a disposable ClickHouse %s server", ClickHouseFile, ClickHouseVersion)

const clickHouseHeader = `# The event store's schema its migrations install (internal/eventstore), read
# back from ClickHouse %s; {database} is Config.ClickHouse.Database.
# Generated by go run ./scripts/contracts -write -clickhouse ADDR; do not edit.
`

// ClickHouseMigrations is one line per event store migration with its digest.
func ClickHouseMigrations() ([]string, error) {
	migrations, err := eventstore.Migrations()
	if err != nil {
		return nil, err
	}
	lines := make([]string, len(migrations))
	for i, m := range migrations {
		lines[i] = "migration " + m.Name + " sha256:" + m.Checksum
	}
	return lines, nil
}

// CheckClickHouseMigrations fails when list was not taken from the current
// event store migrations. It needs no server.
func CheckClickHouseMigrations(list []byte) error {
	want, err := ClickHouseMigrations()
	if err != nil {
		return err
	}
	var got []string
	for line := range strings.Lines(string(list)) {
		if strings.HasPrefix(line, "migration ") {
			got = append(got, strings.TrimSuffix(line, "\n"))
		}
	}
	if !slices.Equal(got, want) {
		return ErrClickHouseStale
	}
	return nil
}

// CaptureClickHouse migrates a scratch database on the server addr names
// (host:port, or a clickhouse:// DSN) and returns the list. The scratch
// database is dropped.
func CaptureClickHouse(ctx context.Context, addr string) ([]byte, error) {
	opts := &clickhouse.Options{Addr: []string{addr}}
	if strings.Contains(addr, "://") {
		var err error
		if opts, err = clickhouse.ParseDSN(addr); err != nil {
			return nil, fmt.Errorf("clickhouse snapshot: %w", err)
		}
	}
	conn, err := clickhouse.Open(opts)
	if err != nil {
		return nil, fmt.Errorf("clickhouse snapshot: %w", err)
	}
	defer conn.Close()
	var version string
	if err := conn.QueryRow(ctx, "SELECT version()").Scan(&version); err != nil {
		return nil, fmt.Errorf("clickhouse snapshot: %w", err)
	}
	if !strings.HasPrefix(version, ClickHouseVersion+".") {
		return nil, fmt.Errorf("clickhouse snapshot: %s is read from ClickHouse %s; this server is %s", ClickHouseFile, ClickHouseVersion, version)
	}
	var suffix [6]byte
	_, _ = rand.Read(suffix[:])
	database := "openrails_schema_" + hex.EncodeToString(suffix[:])
	defer func() {
		ctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 30*time.Second)
		defer cancel()
		_ = conn.Exec(ctx, "DROP DATABASE IF EXISTS `"+database+"` SYNC")
	}()
	if err := eventstore.Migrate(ctx, conn, database, eventstore.Options{Logger: slog.New(slog.DiscardHandler)}); err != nil {
		return nil, fmt.Errorf("clickhouse snapshot: %w", err)
	}
	list, err := dumpClickHouse(ctx, conn, database)
	if err != nil {
		return nil, fmt.Errorf("clickhouse snapshot: %w", err)
	}
	return list, nil
}

func dumpClickHouse(ctx context.Context, conn driver.Conn, database string) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, clickHouseHeader, ClickHouseVersion)
	migrations, err := ClickHouseMigrations()
	if err != nil {
		return nil, err
	}
	for _, line := range migrations {
		out.WriteString(line + "\n")
	}
	anonymous := func(s string) string {
		s = strings.ReplaceAll(s, "`"+database+"`", "{database}")
		return strings.ReplaceAll(s, database, "{database}")
	}
	type column struct{ table, line string }
	rows, err := conn.Query(ctx, `SELECT table, name, type, default_kind, default_expression, compression_codec
		FROM system.columns WHERE database = ? ORDER BY table, position`, database)
	if err != nil {
		return nil, err
	}
	var columns []column
	for rows.Next() {
		var table, name, typ, kind, expr, codec string
		if err := rows.Scan(&table, &name, &typ, &kind, &expr, &codec); err != nil {
			rows.Close()
			return nil, err
		}
		line := "column " + name + " " + typ
		if kind != "" {
			line += " " + kind + " " + expr
		}
		if codec != "" {
			line += " " + codec
		}
		columns = append(columns, column{table, line})
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	rows, err = conn.Query(ctx, `SELECT name, engine, engine_full, as_select, create_table_query
		FROM system.tables WHERE database = ? ORDER BY name`, database)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		var name, engine, full, asSelect, create string
		if err := rows.Scan(&name, &engine, &full, &asSelect, &create); err != nil {
			return nil, err
		}
		switch engine {
		case "MaterializedView":
			target := ""
			if _, after, ok := strings.Cut(create, " TO "); ok {
				target, _, _ = strings.Cut(after, " ")
			}
			fmt.Fprintf(&out, "\nmaterialized view %s TO %s\n  %s\n", name, anonymous(target), anonymous(lineBreak.ReplaceAllString(asSelect, " ")))
			continue
		case "View":
			// The store's identity is its one row; its value is not schema.
			fmt.Fprintf(&out, "\nview %s\n", name)
		default:
			fmt.Fprintf(&out, "\ntable %s\n  engine %s\n", name, anonymous(full))
		}
		for _, c := range columns {
			if c.table == name {
				out.WriteString("  " + c.line + "\n")
			}
		}
	}
	return out.Bytes(), rows.Err()
}
