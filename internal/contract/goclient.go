// The Go Client: a method per client route, generated, but for the routes
// declared HandWritten, whose methods are in handWrittenFile with the
// methods no route has.
const (
	ClientFile      = "client_gen.go"
	handWrittenFile = "client_handwritten.go"
)

// handWrittenMethods are the exported Client methods that call no route of
// their own.
var handWrittenMethods = []string{"ActingFor", "CheckEntitlementsLive", "CustomerAssertion", "CustomerToken", "EventReader", "MerchantID", "Uncached"}

// goClient renders ClientFile from the client routes, after checking that
// the root package declares every other exported Client method in
// handWrittenFile, and only those.
func goClient(fsys fs.FS, list []routes.Route) ([]byte, error) {
	declared := slices.Clone(handWrittenMethods)
	var generate []routes.Route
	for _, r := range list {
		switch {
		case !r.ClientMethod():
		case r.Client == routes.HandWritten:
			declared = append(declared, r.Name)
		default:
			generate = append(generate, r)
		}
	}
	if err := checkHandWritten(fsys, declared); err != nil {
		return nil, err
	}
	imports := map[string]bool{"context": true, "net/http": true}
	var body bytes.Buffer
	for _, r := range generate {
		method, err := clientMethod(r, imports)
		if err != nil {
			return nil, fmt.Errorf("contract: %s: %w", r.Key(), err)
		}
		body.WriteString(method)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `go run ./scripts/contracts -write` from the route catalog. DO NOT EDIT.\n\npackage openrails\n\nimport (\n")
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Slice(paths, func(i, j int) bool {
		if std := !strings.Contains(paths[i], "."); std != !strings.Contains(paths[j], ".") {
			return std
		}
		return paths[i] < paths[j]
	})
	for i, p := range paths {
		if i > 0 && !strings.Contains(paths[i-1], ".") && strings.Contains(p, ".") {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "\t%q\n", p)
	}
	b.WriteString(")\n")
	b.Write(body.Bytes())
	return format.Source(b.Bytes())
}

// checkHandWritten requires each declared method in handWrittenFile and no
// other exported Client method outside ClientFile: a generated one written
// by hand is refused too.
func checkHandWritten(fsys fs.FS, declared []string) error {
	entries, err := fs.ReadDir(fsys, ".")
	if err != nil {
		return err
	}
	found := map[string]bool{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == ClientFile {
			continue
		}
		src, err := fs.ReadFile(fsys, name)
		if err != nil {
			return err
		}
		file, err := parser.ParseFile(token.NewFileSet(), name, src, parser.SkipObjectResolution)
		if err != nil {
			return fmt.Errorf("contract: parse %s: %w", name, err)
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || !fn.Name.IsExported() || !receivesClient(fn) {
				continue
			}
			method := fn.Name.Name
			switch {
			case name != handWrittenFile:
				return fmt.Errorf("contract: %s declares Client.%s: a client method is generated from its route, or declared HandWritten in %s", name, method, handWrittenFile)
			case !slices.Contains(declared, method):
				return fmt.Errorf("contract: %s declares Client.%s, which no HandWritten route names", handWrittenFile, method)
			}
			found[method] = true
		}
	}
	for _, method := range declared {
		if !found[method] {
			return fmt.Errorf("contract: %s lacks Client.%s", handWrittenFile, method)
		}
	}
	return nil
}

func receivesClient(fn *ast.FuncDecl) bool {
	star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := star.X.(*ast.Ident)
	return ok && id.Name == "Client"
}

// clientMethod is one route's method: (ctx, [idempotencyKey], path
// arguments, [body], [query]) answering its success body, or only an error.
func clientMethod(r routes.Route, imports map[string]bool) (string, error) {
	wildcards := pathParams(r.Path)
	params := []string{"ctx context.Context"}
	fields := []string{"method: http.Method" + methodName(r.Method), fmt.Sprintf("path: %q", r.Path)}
	if r.IdempotencyKey {
		params = append(params, "idempotencyKey string")
		fields = append(fields, "idempotencyKey: idempotencyKey")
	}
	var args []string
	for i, w := range wildcards {
		t := reflect.TypeOf(r.Args[i])
		name := lowerCamel(w)
		typ, err := goType(t, imports)
		if err != nil {
			return "", err
		}
		params = append(params, name+" "+typ)
		if _, ok := r.Args[i].(fmt.Stringer); ok {
			args = append(args, name+".String()")
		} else if t.Name() != "string" {
			args = append(args, "string("+name+")")
		} else {
			args = append(args, name)
		}
	}
	if len(args) > 0 {
		fields = append(fields, "args: []string{"+strings.Join(args, ", ")+"}")
	}
	batch := ""
	if r.Request != nil {
		t := reflect.TypeOf(r.Request)
		typ, err := goType(t, imports)
		if err != nil {
			return "", err
		}
		switch member, ok := batchMember(t, "BatchParams"); {
		case ok:
			elem, err := goType(member.Type, imports)
			if err != nil {
				return "", err
			}
			batch = lowerCamel(member.Name)
			params = append(params, batch+" "+elem)
			fields = append(fields, fmt.Sprintf("body: %s{%s: %s}", typ, member.Name, batch))
		case r.Query != nil:
			name := lowerCamel(elem(t).Name())
			params = append(params, name+" "+typ)
			fields = append(fields, "body: "+name)
		default:
			params = append(params, "params "+typ)
			fields = append(fields, "body: params")
		}
	}
	if r.Query != nil {
		typ, err := goType(reflect.TypeOf(r.Query), imports)
		if err != nil {
			return "", err
		}
		params = append(params, "params "+typ)
		fields = append(fields, "query: params")
	}
	if r.Cache != "" {
		imports[module+"/internal/config"] = true
		fields = append(fields, "cache: config."+cacheConst(string(r.Cache)))
	}
	var answer reflect.Type
	for _, reply := range r.Responses {
		if reply.Body == nil {
			continue
		}
		t := reflect.TypeOf(reply.Body)
		if answer != nil && answer != t {
			return "", fmt.Errorf("answers both %s and %s", answer, t)
		}
		answer = t
	}
	var b strings.Builder
	b.WriteString("\n")
	b.WriteString(comment(r.Doc))
	call := "c.send(ctx, routeCall{" + strings.Join(fields, ", ") + "}, "
	signature := "func (c *Client) " + r.Name + "(" + strings.Join(params, ", ") + ")"
	if answer == nil {
		fmt.Fprintf(&b, "%s error {\n\treturn %snil)\n}\n", signature, call)
		return b.String(), nil
	}
	typ, err := goType(answer, imports)
	if err != nil {
		return "", err
	}
	if member, ok := batchMember(answer, "BatchResult"); ok && batch != "" {
		items, err := goType(member.Type, imports)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "%s (%s, error) {\n\tvar out %s\n\tif err := %s&out); err != nil {\n\t\treturn nil, err\n\t}\n\treturn out.%s, nil\n}\n",
			signature, items, typ, call, member.Name)
		return b.String(), nil
	}
	fmt.Fprintf(&b, "%s (*%s, error) {\n\tvar out %s\n\tif err := %s&out); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n",
		signature, typ, typ, call)
	return b.String(), nil
}

// batchMember is the one member, a list, of a batch type named …suffix: the
// method takes or answers the list itself.
func batchMember(t reflect.Type, suffix string) (reflect.StructField, bool) {
	t = elem(t)
	if t.Kind() != reflect.Struct || !strings.HasSuffix(t.Name(), suffix) || t.NumField() != 1 {
		return reflect.StructField{}, false
	}
	f := t.Field(0)
	return f, f.Type.Kind() == reflect.Slice
}

func methodName(method string) string {
	return method[:1] + strings.ToLower(method[1:])
}

// cacheConst is the internal/config constant of a read: catalog is
// ReadCatalog.
func cacheConst(read string) string {
	return "Read" + camel(read)
}

// lowerCamel is a Go parameter name: customer_id is customerID, Items is
// items, RequestIDs is requestIDs.
func lowerCamel(name string) string {
	if strings.ContainsAny(name, "_") || strings.ToLower(name) == name {
		parts := strings.Split(name, "_")
		for i := 1; i < len(parts); i++ {
			if parts[i] == "id" || parts[i] == "ids" {
				parts[i] = strings.ToUpper(parts[i][:2]) + parts[i][2:]
			} else {
				parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
			}
		}
		return strings.Join(parts, "")
	}
	r := []rune(name)
	i := 0
	for i < len(r) && unicode.IsUpper(r[i]) {
		i++
	}
	if i > 1 && i < len(r) {
		i-- // RequestIDs: only the leading word
	}
	if i == 0 {
		i = 1
	}
	return strings.ToLower(string(r[:i])) + string(r[i:])
}

var typeArgument = regexp.MustCompile(`([\w./-]+)\.(\w+)`)

// goType is t as the root package spells it, recording its imports. A type
// from an internal package has no place in a client signature.
func goType(t reflect.Type, imports map[string]bool) (string, error) {
	switch {
	case t.Name() == "" && t.Kind() == reflect.Pointer:
		inner, err := goType(t.Elem(), imports)
		return "*" + inner, err
	case t.Name() == "" && t.Kind() == reflect.Slice:
		inner, err := goType(t.Elem(), imports)
		return "[]" + inner, err
	case t.Name() == "":
		return "", fmt.Errorf("%s has no name", t)
	case t.PkgPath() == "":
		return t.Name(), nil
	}
	var err error
	name := typeArgument.ReplaceAllStringFunc(t.Name(), func(arg string) string {
		m := typeArgument.FindStringSubmatch(arg)
		if e := clientPackage(m[1]); e != nil {
			err = e
		}
		imports[m[1]] = true
		return path.Base(m[1]) + "." + m[2]
	})
	if e := clientPackage(t.PkgPath()); e != nil {
		return "", e
	}
	imports[t.PkgPath()] = true
	return path.Base(t.PkgPath()) + "." + name, err
}

func clientPackage(pkg string) error {
	if !strings.HasPrefix(pkg, module+"/") || strings.Contains(pkg, "/internal") {
		return fmt.Errorf("%s is not a package hosts import", pkg)
	}
	return nil
}

// comment is doc as a Go comment, wrapped to fit.
func comment(doc string) string {
	var b strings.Builder
	for i, para := range strings.Split(doc, "\n\n") {
		if i > 0 {
			b.WriteString("//\n")
		}
		line := "//"
		for _, word := range strings.Fields(para) {
			if len(line)+1+len(word) > 77 && line != "//" {
				b.WriteString(line + "\n")
				line = "//"
			}
			line += " " + word
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}
